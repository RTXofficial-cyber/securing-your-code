const IS_WIN = process.platform === 'win32';

const models = [{ id: 'studio-agent-1', name: 'Studio Agent v1 (built-in)' }];

function lastUser(messages) {
  for (let i = messages.length - 1; i >= 0; i--) {
    if (messages[i].role === 'user') return String(messages[i].content || '');
  }
  return '';
}

function action(type, payload) {
  return '```action:' + type + '\n' + JSON.stringify(payload, null, 2) + '\n```';
}

const NODE_APP = `// Generated by Dev Studio
function greet(name) {
  return \`Hello, \${name}! Built with Dev Studio.\`;
}

console.log(greet(process.argv[2] || 'world'));
console.log('Node version:', process.version);
console.log('Platform:', process.platform);
`;

const PY_APP = `"""Generated by Dev Studio - a tiny HTTP server."""
from http.server import BaseHTTPRequestHandler, HTTPServer


class Handler(BaseHTTPRequestHandler):
    def do_GET(self):
        self.send_response(200)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.end_headers()
        self.wfile.write(b"<h1>Dev Studio</h1><p>Your app is running.</p>")

    def log_message(self, *args):
        pass


if __name__ == "__main__":
    port = 8080
    print(f"Serving on http://localhost:{port}")
    HTTPServer(("127.0.0.1", port), Handler).serve_forever()
`;

async function chat(model, messages) {
  const text = lastUser(messages).toLowerCase();
  const py = IS_WIN ? 'py' : 'python3';

  if (/(web ?app|website|server|http|flask|api)/.test(text)) {
    return [
      "I'll scaffold a small web server for you and verify the runtime is available.",
      action('write_file', { path: 'app.py', content: PY_APP }),
      action('run_command', { command: `${py} --version` }),
      `Created **app.py** — a dependency-free HTTP server. Start it from the terminal with \`${py} app.py\`, then open http://localhost:8080. Want routes, a database, or a frontend next?`
    ].join('\n\n');
  }

  if (/(script|hello|node|javascript|\bjs\b|program|function|code)/.test(text)) {
    return [
      "Here's a working Node.js script. I'll write it into your workspace and run it to prove it works.",
      action('write_file', { path: 'hello.js', content: NODE_APP }),
      action('run_command', { command: 'node hello.js DevStudio' }),
      "**hello.js** is in your workspace — open it from the file tree to edit it, or ask me to extend it."
    ].join('\n\n');
  }

  if (/(list|show).*(file|project|workspace)|what.*(file|built)/.test(text)) {
    return ["Let me look at your workspace.", action('list_files', {}), "Those are the files in your project right now. Ask me to create, edit, or run any of them."].join('\n\n');
  }

  if (/(run|execute|test|check)/.test(text)) {
    return [
      "Running an environment check.",
      action('run_command', {
        command: IS_WIN
          ? 'echo --- environment --- && ver && node --version && dir'
          : 'echo "--- environment ---" && uname -a && node --version && ls -la'
      }),
      "That's your current workspace runtime. Tell me what to build next."
    ].join('\n\n');
  }

  return [
    "I'm **Studio Agent v1**, the built-in Dev Studio engine. I can already:",
    "",
    "- **Write files** into your workspace — try: *\"write a node script that greets me\"*",
    "- **Run commands** and show real output — try: *\"run a command to check the environment\"*",
    "- **Scaffold apps** — try: *\"build me a web app\"*",
    "",
    "For full-scale work, connect a frontier model: open **Settings** in the sidebar and paste an API key for Claude, ChatGPT, Perplexity, Gemini or Groq.",
    "",
    "You can also replace me with **your own AI** — it's a single function in `shared/builtin.cjs`."
  ].join('\n');
}

