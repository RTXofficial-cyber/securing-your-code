function kbAnswer(t) {
  const n = norm(t);
  for (const topic of KB) if (topic.m.test(n)) {
    return [`**${topic.t}** — offline crash course:`, ...topic.b.map((x) => `- ${x}`)].join('\n');
  }
  return null;
}

