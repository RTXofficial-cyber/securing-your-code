async function chat(model, messages) {
  const text = lastUser(messages).toLowerCase();

  // When filling a team role in the ensemble pipeline, answer as that role.
  const role = detectRole(messages);
  if (role === 'research') return researchOffline(text);
  if (role === 'plan') return planOffline(text);
  if (role === 'review') return reviewOffline();

  // ---- conversation first: greetings, identity, math, time, concepts ----
  const greet = greetAnswer(text);
  if (greet) return greet;
  const ident = identityAnswer(text);
  if (ident) return ident;
  const thanks = thanksAnswer(text);
  if (thanks) return thanks;
  const clock = timeAnswer(text);
  if (clock) return clock;
  const math = mathAnswer(text);
  if (math) return math;
  const usage = appUsageAnswer(text);
  if (usage) return usage;

  // ---- question-shaped concept queries get explained BEFORE any build ----
  if (isQuestion(text) && !/(write|make|build|create|generate|scaffold)/.test(text)) {
    const kb = kbAnswer(text);
    if (kb) return kb;
  }

  // ---- known build intents ----
  if (/(static site|website|landing|web ?page|portfolio|homepage)/.test(text)) {
    return [
      'Plan: (1) scaffold a dependency-free static site, (2) syntax-check the JS, (3) list what landed.',
      writeAll(SITE),
      run('node --check app.js'),
      list(),
      `Done — a 3-file static site (**index.html**, **styles.css**, **app.js**). Serve it from the terminal with \`${PY} -m http.server 8080\` and open http://localhost:8080. Want a dark theme, more sections, or a contact form next?`
    ].join('\n\n');
  }

  if (/python|flask|django|\bpy\b/.test(text)) {
    return [
      'Plan: (1) write a dependency-free Python HTTP server, (2) byte-compile it to prove it is valid.',
      writeAll(PYAPP),
      run(`${PY} -m py_compile app.py && echo COMPILE_OK`),
      `Created **app.py**. Run \`${PY} app.py\` in the terminal and open http://localhost:8080. Want it to read/write JSON files or serve HTML next?`
    ].join('\n\n');
  }

  if (/\bapi\b|backend|rest|server|http endpoint|microservice/.test(text)) {
    return [
      'Plan: (1) write a dependency-free Node HTTP API, (2) syntax-check it, (3) smoke-test the health route.',
      writeAll(API),
      run('node --check server.js'),
      `Created **server.js** with routes \`/\`, \`/health\` and \`/api/hello?name=you\`. Start it in the terminal with \`node server.js\`, then hit http://localhost:8080/health. I can add POST routes, JSON persistence, or auth next.`
    ].join('\n\n');
  }

  if (/\bcli\b|command line|command-line tool|argparse|terminal app/.test(text)) {
    return [
      'Plan: (1) write a CLI with flags, (2) run its --help, (3) run it for real.',
      writeAll(CLI),
      run('node cli.js --help'),
      run('node cli.js --name DevStudio --loud'),
      'Created **cli.js**. Try `node cli.js --name You --loud` in the terminal. I can add subcommands, config files, or packaging next.'
    ].join('\n\n');
  }

  if (/game|playable|snake|reflex|arcade|platformer|shooter|runner/.test(text)) {
    const genre = (function () {
      if (/platform|jump|mario/.test(text)) return 'platformer';
      if (/runner|endless|dash|flappy/.test(text)) return 'runner';
      if (/shooter|shmup|space|star|invaders/.test(text)) return 'shmup';
      return 'arena';
    })();
    const names = { arena: 'VOID ARENA (twin-stick survival)', platformer: 'MONO JUMP (precision platformer)', shmup: 'STARFALL (vertical shooter)', runner: 'LINE RUNNER (endless runner)' };
    return [
      `Plan: (1) scaffold **${names[genre]}** with the GameKit engine, (2) syntax-verify it, (3) tell you how to play.`,
      action('game_new', { genre, dir: 'game' }),
      action('game_check', { dir: 'game' }),
      `Done — a complete game is in **game/**: fixed-timestep loop, particles, screen shake, hit-stop, synth SFX, pause, high-score save and gamepad support. Press the **▶ play** button in the activity bar (or open \`game/index.html\`). Want a different genre? Say "make a platformer / runner / space shooter".`
    ].join('\n\n');
  }

  if (/todo|task|checklist|kanban/.test(text)) {
    return [
      'Plan: (1) write a single-file todo app with localStorage persistence, (2) confirm it landed.',
      writeAll(TODO),
      list(),
      'Created **todo.html** — tasks persist in localStorage. Open it in a browser. I can add due dates, filters, or export next.'
    ].join('\n\n');
  }

  if (/(list|show).*(file|project|workspace)|what.*(file|built)/.test(text)) {
    return ['Looking at your workspace now.', list(), 'Those are the files in your project. Ask me to create, edit, or run any of them.'].join('\n\n');
  }

  if (/(run|execute|test|check|environment)/.test(text)) {
    return [
      'Running an environment check.',
      run(IS_WIN ? 'echo --- environment --- && ver && node --version && dir' : 'echo "--- environment ---" && uname -a && node --version && ls -la'),
      "That's your current workspace runtime. Tell me what to build next."
    ].join('\n\n');
  }

  if (/(script|hello|node|javascript|\bjs\b|program|function|code)/.test(text)) {
    return [
      'Plan: (1) write the script, (2) run it to prove it works.',
      writeAll(NODE_HELLO),
      run('node hello.js DevStudio'),
      '**hello.js** is in your workspace — open it from the file tree, or ask me to turn it into a CLI, an API, or a site.'
    ].join('\n\n');
  }

  // ---- concepts crash-course (question-shaped or "explain ...") ----
  if (isQuestion(text) || /explain|samjhao|define|meaning of/.test(text)) {
    const kb = kbAnswer(text);
    if (kb) return kb;
  }

  // ---- "change/add/fix something" in an existing project ----
  const mod = modifyAnswer(text);
  if (mod) return mod;

  // ---- anything else: a question-aware answer, never a canned intro ----
  if (text.trim()) return openAnswer(lastUser(messages), text);

  return [
    "I'm **Studio Agent v2**, Dev Studio's built-in offline engine. I plan, write whole projects, and verify them by compiling or running — no internet, no API key.",
    '',
    'Try any of these and I will build the real thing in your workspace:',
    '- *"build me a website"* → 3-file static site (HTML/CSS/JS)',
    '- *"create an api"* → dependency-free Node HTTP API',
    '- *"make a python server"* → Python HTTP server, byte-compiled to verify',
    '- *"write a cli tool"* → CLI with flags, then I run it',
    '- *"make a game"* / *"make a todo app"* → single-file browser apps',
    '',
    'You can also ask me concepts (recursion, git, SQL, CSS, security…) or math.',
    'For open-ended research, connect a frontier model in **Settings** (Claude, ChatGPT, Perplexity, Gemini, Groq).'
  ].join('\n');
}

