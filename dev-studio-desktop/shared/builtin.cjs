function lastUser(messages) {
  for (let i = messages.length - 1; i >= 0; i--) {
    if (messages[i].role === 'user') return String(messages[i].content || '');
  }
  return '';
}

function action(type, payload) {
  return '```action:' + type + '\n' + JSON.stringify(payload, null, 2) + '\n```';
}
const writeFile = (path, content) => action('write_file', { path, content });
const run = (command) => action('run_command', { command });
const list = () => action('list_files', {});

