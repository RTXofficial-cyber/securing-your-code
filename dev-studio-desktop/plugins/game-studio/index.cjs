/**
 * Official plugin: Game Studio.
 *
 * Gives the AI three actions:
 *   action:game_new    {"genre":"arena|platformer|shmup|runner","dir":"game"}
 *   action:game_check  {"dir":"game"}
 *   action:game_list   {}
 *
 * game_new copies the GameKit engine + a full genre template into the
 * workspace, so "make a game" produces a playable, juicy, finished game —
 * not a stub. Everything is zero-dependency and runs from a double-click.
 */
const fs = require('fs');
const path = require('path');

const KIT = path.join(__dirname, '..', '..', 'shared', 'gamekit');
const { parseSpec, describeSpec } = require('../../shared/gamekit/spec.cjs');
const { describeSpec3d } = require('../../shared/gamekit/spec3d.cjs');

const PRESETS = { arena: 'arena', platformer: 'platformer', shmup: 'shmup', runner: 'runner', city: 'city', city3d: 'city3d' };

const GENRES = {
  city3d: ['3d', 'first person', 'first-person', 'fps city', '3d city'],
  city: ['gta', 'grand theft', 'open world', 'open-world', 'crime', 'mafia', 'heist', 'police chase', 'car game', 'driving', 'city'],
  arena: ['arena', 'twin-stick', 'survival', 'top-down', 'topdown'],
  platformer: ['platformer', 'platform', 'jump', 'mario', 'metroidvania'],
  shmup: ['shmup', 'shooter', 'space', 'star', 'invaders', 'bullet'],
  runner: ['runner', 'run', 'endless', 'dash', 'flappy']
};

function genreOf(text) {
  const t = String(text || '').toLowerCase();
  for (const [genre, words] of Object.entries(GENRES)) {
    if (words.some((w) => t.includes(w))) return genre;
  }
  return 'arena';
}

const PAGE = (title, extra = '') => `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${title}</title>
    <style>
      html, body { margin:0; height:100%; background:#0b0b0b; display:flex; align-items:center; justify-content:center; overflow:hidden; }
      canvas { max-width:100%; max-height:100%; box-shadow:0 0 0 1px #2a2a2a; border-radius:10px; }
    </style>
  </head>
  <body>
    <canvas id="game" width="960" height="540"></canvas>
    <script src="./engine.js"></script>
    ${extra}<script src="./game.js"></script>
  </body>
</html>
`;

module.exports = {
  tools: [
    {
      name: 'game_new',
      description: 'Scaffold a complete game into the workspace. Params: { "genre": "arena|platformer|shmup|runner|city", "dir": "game" }',
      run: (a, ctx) => {
        try {
          const dir = String(a?.dir || 'game').replace(/[^a-z0-9_/-]/gi, '') || 'game';
          // An explicit spec (from the AI, parsed from the user's sentence) wins.
          // A bare preset name ("make a platformer") uses the hand-tuned template.
          const spec3d = a.spec3d || null;
          const preset = !a.spec && !spec3d ? PRESETS[String(a?.genre || '').toLowerCase()] : null;
          const spec = a.spec || parseSpec(a?.request || a?.genre || '');
          const engine = fs.readFileSync(path.join(KIT, 'engine.js'), 'utf8');
          let game;
          if (spec3d) {
            const composed3d = fs.readFileSync(path.join(KIT, 'templates', 'composed3d.js'), 'utf8');
            game = `// Generated by Dev Studio Game Studio 3D from: "${String(spec3d.seedText || '').replace(/"/g, "'")}"\nconst GAME_SPEC3D = ${JSON.stringify(spec3d, null, 2)};\n` + composed3d;
          } else if (preset) {
            game = fs.readFileSync(path.join(KIT, 'templates', `${preset}.js`), 'utf8');
          } else {
            const composed = fs.readFileSync(path.join(KIT, 'templates', 'composed.js'), 'utf8');
            game = `// Generated by Dev Studio Game Studio from: "${String(spec.seedText || '').replace(/"/g, "'")}"\nconst GAME_SPEC = ${JSON.stringify(spec, null, 2)};\n` + composed;
          }
          const title = spec3d ? String(spec3d.title || 'COMPOSED 3D').toUpperCase() : preset === 'city' ? 'GRAND THEFT MONO' : preset === 'city3d' ? 'MONO CITY 3D' : preset ? preset.toUpperCase() : spec.title;
          ctx.ws.write(`${dir}/engine.js`, engine);
          if (spec3d || preset === 'city3d') ctx.ws.write(`${dir}/engine3d.js`, fs.readFileSync(path.join(KIT, 'engine3d.js'), 'utf8'));
          ctx.ws.write(`${dir}/game.js`, game);
          ctx.ws.write(`${dir}/index.html`, PAGE(`DEV STUDIO — ${title}`, (spec3d || preset === 'city3d') ? '<script src="./engine3d.js"></script>\n    ' : ''));
          return {
            ok: true,
            genre: spec3d ? `3d:${spec3d.control}` : preset || spec.control,
            spec: spec3d || spec,
            mechanics: spec3d ? describeSpec3d(spec3d) : preset ? `hand-tuned ${preset} template` : describeSpec(spec),
            dir,
            files: (spec3d || preset === 'city3d') ? [`${dir}/index.html`, `${dir}/engine.js`, `${dir}/engine3d.js`, `${dir}/game.js`] : [`${dir}/index.html`, `${dir}/engine.js`, `${dir}/game.js`],
            play: `Open ${dir}/index.html in a browser, or press the ▶ button in Dev Studio.`
          };
        } catch (e) {
          return { ok: false, error: e.message };
        }
      }
    },
    {
      name: 'game_check',
      description: 'Syntax-verify a scaffolded game. Params: { "dir": "game" }',
      run: async (a, ctx) => {
        const dir = String(a?.dir || 'game').replace(/[^a-z0-9_/-]/gi, '') || 'game';
        const r = await ctx.runShell(`node --check ${dir}/game.js && node --check ${dir}/engine.js && echo GAME_SYNTAX_OK`, ctx.workspace, 30000);
        return r;
      }
    },
    {
      name: 'game_list',
      description: 'List games in the workspace and their genres.',
      run: (_a, ctx) => {
        try {
          const tree = ctx.ws.tree();
          const dirs = tree.filter((n) => n.type === 'dir');
          const found = [];
          for (const d of dirs) {
            const kids = (d.children || []).map((c) => c.name);
            if (kids.includes('game.js') && kids.includes('engine.js')) {
              const src = ctx.ws.read(`${d.path}/game.js`).slice(0, 200);
              const title = /GameKit\(\{ title: '([^']+)'/.exec(src);
              found.push({ dir: d.path, title: title ? title[1] : d.path });
            }
          }
          return { ok: true, games: found };
        } catch (e) {
          return { ok: false, error: e.message };
        }
      }
    }
  ]
};

module.exports.genreOf = genreOf;
